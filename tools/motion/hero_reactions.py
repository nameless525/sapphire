def hand_contact(m, target):
    """Reach in model space to the support palm, spreading the fingers on contact."""
    key = m.keys[-1]
    p = key['pose']
    short = solve_left_arm(p, target, (.66, .28, -.64))
    set_rot(p, 'LeftHand', turn(0, -67, -36))
    for bone in ('LeftUpperArm', 'LeftLowerArm', 'LeftHand'):
        euler = to_euler(p.turns[bone])
        key['euler'][bone] = euler
        key['rounded'][bone] = turn(*(round(v, 1) for v in euler))
    if short > .001:
        print(f"  ! {m.name} tick {key['tick']}: support palm short by {short*100:.1f} cm")


