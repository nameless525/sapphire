    #[test]
    fn the_bangs_hang_off_the_forehead_over_the_brows_and_eyes() {
        let bangs = bangs();
        let triangles = bangs.indices.as_chunks::<3>().0;
        for &[a, b, c] in triangles {
            let [a, b, c] = [a, b, c].map(|i| bangs.positions[i as usize]);
            let normal = cross(sub(b, a), sub(c, a));
            let center = [0, 1, 2].map(|i| (a[i] + b[i] + c[i]) / 3.0);
            let out = normal[0] * center[0] + normal[1] * center[1] + normal[2] * center[2];
            assert!(out > 0.0, "wound to face out of the head: {a:?} {b:?} {c:?}");
        }
        for (p, n) in bangs.positions.iter().zip(&bangs.normals) {
            let length = (p[0] * p[0] + p[1] * p[1] + p[2] * p[2]).sqrt();
            assert!(
                (length - BANGS_RADIUS).abs() < 1e-5 && (length - RADIUS) > 0.01,
                "off the forehead: {p:?}"
            );
            assert!((p[0] / length - n[0]).abs() < 1e-5, "the sphere's normals");
        }
        // The longest strands reach down over the eyes' tops, and every strand covers the brows'
        // height in front of the face.
        let lowest = bangs.positions.iter().map(|p| p[1]).fold(f32::INFINITY, f32::min);
        let eye_top = EYE_CENTER.1 + EYE_HALF.1;
        assert!(lowest < eye_top && lowest > EYE_CENTER.1 - EYE_HALF.1, "{lowest}");
        let over_eye = bangs.positions.iter().any(|p| (p[0] - EYE_CENTER.0).abs() < 0.01 && p[1] < eye_top);
        assert!(over_eye, "a strand crosses the eye");
        // Mirror-symmetric, with the mirrored strand coordinate.
        for (p, uv_at) in bangs.positions.iter().zip(&bangs.uvs) {
            let mirror = bangs.positions.iter().zip(&bangs.uvs).any(|(q, w)| {
                (q[0] + p[0]).abs() < 1e-5
                    && (q[1] - p[1]).abs() < 1e-5
                    && (w[0] + uv_at[0] - 1.0).abs() < 1e-5
            });
            assert!(mirror, "{p:?}");
        }
    }

