/// The face material slot's name, which the head's sidecar binds.
pub const FACE_SLOT: &str = "Face";

/// The head's sphere, in meters.
pub const RADIUS: f32 = 0.12;
/// Below the head's center, the sphere is drawn out by this much in Y and narrowed toward the
/// chin by up to this much in X, and less in Z: a jaw.
const JAW_STRETCH: f32 = 1.25;
const JAW_TAPER: f32 = 0.35;
const JAW_FLATTEN: f32 = 0.15;
/// How much of the sphere's elevation the vertical field keeps: an anime face's front is
/// flatter than a sphere, so a top light reaches lower before the face turns dark.
const FACE_FLATNESS: f32 = 0.65;
/// The front projection: meters per UV unit, and the `v` of the head's center.
const UV_SPAN: f32 = 0.3;
const UV_CENTER_V: f32 = 0.45;

/// Maps' size in texels.
const SIZE: u32 = 256;
/// The masks' angles, in degrees: horizontal every 10° from the front to behind, vertical every
/// 15° from the front to overhead.
const HORIZONTAL_ANGLES: [u32; 19] = {
    let mut angles = [0; 19];
    let mut i = 0;
    while i < 19 {
        angles[i] = 10 * i as u32;
        i += 1;
    }
    angles
};
const VERTICAL_ANGLES: [u32; 7] = [0, 15, 30, 45, 60, 75, 90];

/// Every face file, relative to the samples directory, with its bytes.
pub fn files() -> io::Result<Vec<(String, Vec<u8>)>> {
    let path = |name: &str| format!("{DIR}/{name}");
    let mut files = vec![
        (path(HEAD_FILE_NAME), head_glb()),
        (path(SDF_FILE_NAME), sdf_document().into_bytes()),
        (path(BASE_COLOR_FILE_NAME), base_color_png()?),
        (path(MASK_FILE_NAME), mask_png()?),
        (path(EXPRESSION_FILE_NAME), expression_png()?),
        (path(MATERIAL_FILE_NAME), material_document().into_bytes()),
    ];
    for angle in HORIZONTAL_ANGLES {
        files.push((
            path(&horizontal_mask_name(angle)),
            threshold_mask_png(angle as f32, horizontal_threshold)?,
        ));
    }
    for angle in VERTICAL_ANGLES {
        files.push((path(&vertical_mask_name(angle)), threshold_mask_png(angle as f32, vertical_threshold)?));
    }
    Ok(files)
}

fn horizontal_mask_name(angle: u32) -> String {
    format!("masks/h_{angle:03}.png")
}

fn vertical_mask_name(angle: u32) -> String {
    format!("masks/v_{angle:03}.png")
}

/// The texture coordinate of head-local point `(x, y)`: a front projection, `x` toward the
/// head's left (+X) and `y` up from the head's center.
pub fn uv(x: f32, y: f32) -> [f32; 2] {
    [0.5 + x / UV_SPAN, UV_CENTER_V - y / UV_SPAN]
}

/// The head-local point a texture coordinate projects from.
fn point(u: f32, v: f32) -> (f32, f32) {
    ((u - 0.5) * UV_SPAN, (UV_CENTER_V - v) * UV_SPAN)
}

/// The jaw's narrowing at sphere height `y`: 1 above the center, less toward the chin.
fn taper(y: f32) -> f32 {
    if y >= 0.0 { 1.0 } else { 1.0 - JAW_TAPER * (y / RADIUS).powi(2) }
}

/// A sphere point moved onto the head: the lower half drawn out and narrowed into a jaw.
fn head_point([x, y, z]: [f32; 3]) -> [f32; 3] {
    if y >= 0.0 {
        return [x, y, z];
    }
    let flatten = 1.0 - JAW_FLATTEN * (y / RADIUS).powi(2);
    [x * taper(y), y * JAW_STRETCH, z * flatten]
}

/// The sphere point under head-local front point `(x, y)`, as `(x, y, z)` on the undeformed
/// sphere, or `None` outside the head's outline.
fn sphere_point(x: f32, y: f32) -> Option<[f32; 3]> {
    let y = if y >= 0.0 { y } else { y / JAW_STRETCH };
    if y.abs() > RADIUS {
        return None;
    }
    let x = x / taper(y);
    let z_squared = RADIUS * RADIUS - x * x - y * y;
    (z_squared >= 0.0).then(|| [x, y, z_squared.sqrt()])
}

/// Whether head-local point `(x, y)` lies within a few texels of the head's outline: maps paint
/// a margin past it, so filtering at the silhouette reads face values.
fn near_head(x: f32, y: f32) -> bool {
    let margin = 3.0 * UV_SPAN / SIZE as f32;
    let shrink = 1.0 - margin / RADIUS;
    sphere_point(x * shrink, y * shrink).is_some()
}

/// The angles of the head's normal under head-local front point `(x, y)`, in degrees:
/// `(azimuth toward +X, elevation)`, each in the plane its channel's light turns in. A point in
/// the margin past the outline takes the angles of the outline beside it, so the margin
/// continues the face's values outward.
fn normal_angles(x: f32, y: f32) -> (f32, f32) {
    let sy = if y >= 0.0 { y } else { y / JAW_STRETCH }.clamp(-0.999 * RADIUS, 0.999 * RADIUS);
    let level = (RADIUS * RADIUS - sy * sy).sqrt();
    let sx = (x / taper(sy)).clamp(-0.999 * level, 0.999 * level);
    let sz = (level * level - sx * sx).max(0.0).sqrt();
    let azimuth = (sx / level).asin().to_degrees();
    let elevation = sy.atan2(sz).to_degrees();
    (azimuth, elevation)
}

/// A soft bump: 1 at `center`, falling off over `radii`.
fn bump(x: f32, y: f32, center: (f32, f32), radii: (f32, f32)) -> f32 {
    let (dx, dy) = ((x - center.0) / radii.0, (y - center.1) / radii.1);
    (-(dx * dx + dy * dy)).exp()
}

/// The horizontal channel's field: the light angle, in degrees from the front toward the head's
/// right (-X), at which head-local point `(x, y)` turns to shadow. A sphere's terminator: the
/// right half lit to past 90°, the left (far) half dark sooner. Then the anime shapes: the
/// nose's shadow on its far side appears at 38°, as a triangle widening down to the tip, and the
/// far cheek under the eye stays lit 16° longer, so the edge bows around it.
pub fn horizontal_threshold(x: f32, y: f32) -> Option<f32> {
    if !near_head(x, y) {
        return None;
    }
    let (azimuth, _) = normal_angles(x, y);
    let mut angle = 90.0 - azimuth;
    if x > 0.0 {
        angle += 16.0 * bump(x, y, (0.04, -0.045), (0.028, 0.022));
    }
    let (top, tip) = (-0.022, -0.052);
    if (tip..top).contains(&y) {
        let width = 0.014 * (top - y) / (top - tip);
        if (0.002..0.002 + width).contains(&x) {
            angle = angle.min(38.0);
        }
    }
    Some(angle.clamp(10.0, 180.0))
}

/// The vertical channel's field: the light angle, in degrees from the front rising toward
/// overhead, at which `(x, y)` turns to shadow. A sphere's, flattened as an anime face is: the
/// forehead lit longest, the chin least, the lower face going dark below the mouth only past
/// about 60°. Then a top light's anime shapes, each an ellipse: the eye sockets under the brows
/// dark past 52°, under the nose past 34°, under the lower lip past 40°. Everything is lit by a
/// light straight ahead up to 15° above it.
pub fn vertical_threshold(x: f32, y: f32) -> Option<f32> {
    if !near_head(x, y) {
        return None;
    }
    let (_, elevation) = normal_angles(x, y);
    let mut angle = 90.0 + FACE_FLATNESS * elevation;
    let shapes = [
        // Eye sockets, under the brows.
        ((0.044, 0.01), (0.028, 0.013), 52.0),
        // Under the nose.
        ((0.0, -0.058), (0.009, 0.006), 34.0),
        // Under the lower lip.
        ((0.0, -0.103), (0.016, 0.007), 40.0),
    ];
    for ((cx, cy), (rx, ry), limit) in shapes {
        if ((x.abs() - cx) / rx).hypot((y - cy) / ry) < 1.0 {
            angle = angle.min(limit);
        }
    }
    Some(angle.clamp(15.0, 180.0))
}

/// The face's lit region with the light `angle` degrees along `field`: white where lit.
fn threshold_mask_png(angle: f32, field: fn(f32, f32) -> Option<f32>) -> io::Result<Vec<u8>> {
    gray_png(|u, v| {
        let (x, y) = point(u, v);
        f32::from(field(x, y).is_some_and(|threshold| threshold > angle))
    })
}

/// The face map's document: the masks at their angles.
pub fn sdf_document() -> String {
    let masks = |angles: &[u32], name: fn(u32) -> String| {
        angles.iter().map(|&angle| ThresholdMask { angle: angle as f32, path: name(angle) }).collect()
    };
    let document = FaceSdfMap {
        horizontal: masks(&HORIZONTAL_ANGLES, horizontal_mask_name),
        vertical: masks(&VERTICAL_ANGLES, vertical_mask_name),
        allowed_violations: 0,
    };
    document.validate().expect("the face's masks are in order");
    sapphire_serialize::to_ron(&document).expect("a face SDF document serializes")
}

/// Coverage of an ellipse around `center` with `half` extents at `(x, y)`, anti-aliased over a
/// texel.
fn ellipse(x: f32, y: f32, center: (f32, f32), half: (f32, f32)) -> f32 {
    let k = ((x - center.0) / half.0).hypot((y - center.1) / half.1);
    let texel = UV_SPAN / SIZE as f32 / half.0.min(half.1);
    smoothstep(1.0 + texel, 1.0 - texel, k)
}

/// Coverage of a stroke `width` wide from `a` to `b`, anti-aliased over a texel.
fn stroke(x: f32, y: f32, a: (f32, f32), b: (f32, f32), width: f32) -> f32 {
    let (dx, dy) = (b.0 - a.0, b.1 - a.1);
    let t = (((x - a.0) * dx + (y - a.1) * dy) / (dx * dx + dy * dy)).clamp(0.0, 1.0);
    let distance = (x - a.0 - t * dx).hypot(y - a.1 - t * dy);
    let texel = UV_SPAN / SIZE as f32;
    smoothstep(0.5 * width + texel, 0.5 * width - texel, distance)
}

fn smoothstep(edge0: f32, edge1: f32, x: f32) -> f32 {
    let t = ((x - edge0) / (edge1 - edge0)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

/// One eye's painted parts at `(x, y)`, for the eye centered at `cx` (mirrored for the other
/// side): sclera, iris, pupil, highlight and lashes, each a coverage.
struct Eye {
    sclera: f32,
    iris: f32,
    pupil: f32,
    highlight: f32,
    lashes: f32,
}

const EYE_CENTER: (f32, f32) = (0.042, -0.012);
const EYE_HALF: (f32, f32) = (0.019, 0.023);

fn eye(x: f32, y: f32) -> Eye {
    // Both eyes alike: the left one mirrored onto the right.
    let x = x.abs();
    let (cx, cy) = EYE_CENTER;
    let sclera = ellipse(x, y, EYE_CENTER, EYE_HALF);
    let iris = ellipse(x, y, (cx - 0.001, cy - 0.003), (0.0135, 0.0195)) * sclera;
    let pupil = ellipse(x, y, (cx - 0.001, cy - 0.005), (0.0055, 0.009)) * sclera;
    let highlight = ellipse(x, y, (cx - 0.006, cy + 0.006), (0.0038, 0.0045));
    // A heavy upper lash line along the top of the eye, winged outward, and a thin lower one.
    let ring = ellipse(x, y, EYE_CENTER, (EYE_HALF.0 * 1.25, EYE_HALF.1 * 1.18)) * (1.0 - sclera);
    let upper = ring * smoothstep(cy + 0.002, cy + 0.008, y);
    let wing = stroke(x, y, (cx + 0.016, cy + 0.012), (cx + 0.027, cy + 0.017), 0.0035);
    let lower = ellipse(x, y, (cx, cy + 0.001), (EYE_HALF.0 * 1.06, EYE_HALF.1 * 1.04))
        * (1.0 - sclera)
        * smoothstep(cy - 0.012, cy - 0.018, y)
        * 0.6;
    Eye { sclera, iris, pupil, highlight, lashes: upper.max(wing).max(lower) }
}

/// The brows: thin arcs above the eyes.
fn brow(x: f32, y: f32) -> f32 {
    let x = x.abs();
    let (cx, cy) = (0.045, 0.012);
    let outer = ellipse(x, y, (cx, cy), (0.03, 0.026));
    let inner = ellipse(x, y, (cx, cy - 0.0035), (0.03, 0.026));
    (outer - inner).max(0.0) * smoothstep(cy + 0.012, cy + 0.017, y)
}

/// The mouth: a small smile.
fn mouth(x: f32, y: f32) -> f32 {
    let (cy, half) = (-0.078, (0.012, 0.008));
    let outer = ellipse(x, y, (0.0, cy), half);
    let inner = ellipse(x, y, (0.0, cy + 0.0022), half);
    (outer - inner).max(0.0) * smoothstep(cy - 0.002, cy - 0.005, y)
}

/// Linear blend of two 8-bit sRGB colors by `t`, as a paint program layers them.
fn layer(base: [f32; 3], color: [u8; 3], t: f32) -> [f32; 3] {
    std::array::from_fn(|i| base[i] + (f32::from(color[i]) / 255.0 - base[i]) * t)
}

/// The face's albedo: skin, eyes, brows and mouth, in sRGB.
fn base_color(x: f32, y: f32) -> [f32; 3] {
    let mut color = [1.0, 236.0 / 255.0, 226.0 / 255.0];
    let eye = eye(x, y);
    color = layer(color, [252, 251, 255], eye.sclera);
    // The iris darkens toward the top, under the lid's shadow.
    let depth = smoothstep(EYE_CENTER.1 - 0.02, EYE_CENTER.1 + 0.012, y);
    let iris = std::array::from_fn(|i| {
        let (low, high) = ([70.0, 178.0, 205.0], [22.0, 64.0, 112.0]);
        (low[i] + (high[i] - low[i]) * depth) as u8
    });
    color = layer(color, iris, eye.iris);
    color = layer(color, [18, 28, 52], eye.pupil);
    color = layer(color, [255, 255, 255], eye.highlight * eye.sclera);
    color = layer(color, [52, 30, 38], eye.lashes);
    color = layer(color, [96, 58, 50], brow(x, y));
    layer(color, [182, 84, 88], mouth(x, y))
}

/// The face mask: nose line, highlights and always-lit features.
fn mask(x: f32, y: f32) -> [f32; 3] {
    // On the nose's left side, the far one from a camera on the head's right.
    let nose_line = stroke(x, y, (0.0045, -0.03), (0.0085, -0.05), 0.003);
    let highlight = ellipse(x, y, (-0.002, -0.047), (0.0045, 0.0035)).max(ellipse(
        x.abs(),
        y,
        (0.054, -0.034),
        (0.012, 0.0045),
    ));
    let eye = eye(x, y);
    let always_lit = eye.sclera.max(eye.lashes).max(brow(x, y));
    [nose_line, highlight, always_lit]
}

/// The expression map: blush on the cheeks, gloom over the brow.
fn expression(x: f32, y: f32) -> [f32; 3] {
    let k = ((x.abs() - 0.058) / 0.024).hypot((y + 0.05) / 0.012);
    let blush = smoothstep(1.0, 0.35, k);
    let gloom = if near_head(x, y) { smoothstep(-0.016, 0.022, y) } else { 0.0 };
    [blush, gloom, 0.0]
}

fn base_color_png() -> io::Result<Vec<u8>> {
    rgb_png(base_color)
}

fn mask_png() -> io::Result<Vec<u8>> {
    rgb_png(mask)
}

fn expression_png() -> io::Result<Vec<u8>> {
    rgb_png(expression)
}

/// The face material's document.
pub fn material_document() -> String {
    let face = FaceShading {
        mask_map: Some(MASK_ID),
        expression_map: Some(EXPRESSION_ID),
        softness: 0.012,
        nose_line: 0.45,
        highlight: 0.22,
        highlight_reveal: 0.12,
        blush_color: [1.0, 0.5, 0.52],
        ..FaceShading::new(SDF_ID)
    };
    let material = AnimeCharacterMaterial {
        surface: CharacterSurface::Face(face),
        base_color: [1.0; 4],
        base_color_map: Some(BASE_COLOR_ID),
        light_split: LightSplit { threshold: 0.0, softness: 0.0 },
        regions: vec![CharacterRegion {
            shade_color: [0.93, 0.66, 0.64],
            rim_color: [1.0, 0.86, 0.8],
            outline_color: [0.36, 0.15, 0.14],
            // Skin on a face: its GI shades like a ball around the head, in the rig's skin tint.
            gi: RegionGi { sphere: 1.0, skin: 1.0 },
            ..CharacterRegion::default()
        }],
        rim: Rim { width: 0.2, strength: 0.12 },
        outline: Outline { width: 3.0, ..Outline::default() },
        ..AnimeCharacterMaterial::default()
    };
    use sapphire_assets::material::MaterialDocument;
    material.validate().expect("the face material is valid");
    sapphire_serialize::to_ron(&material).expect("a material document serializes")
}

/// Rings and segments of the head's sphere.
const RINGS: u32 = 32;
const SEGMENTS: u32 = 48;

/// The head as a binary glTF: the face (slot [`FACE_SLOT`]) and the hair cap (slot `Hair`, a flat
/// dark material from the Blender extras the glTF importer reads).
pub fn head_glb() -> Vec<u8> {
    let mut gltf = GltfWriter::default();
    let face_material = gltf.add_material(json!({
        "name": FACE_SLOT,
        "pbrMetallicRoughness": { "baseColorFactor": [1.0, 1.0, 1.0, 1.0] },
    }));
    let hair_material = gltf.add_material(json!({
        "name": "Hair",
        "pbrMetallicRoughness": { "baseColorFactor": srgb8(58, 52, 104) },
        "extras": {
            // Flat: the same tone lit and in shadow, so only the face shows the light.
            "shade_color": [1.0, 1.0, 1.0, 1.0],
            "outline_color": srgb8(24, 20, 44),
            "character_shading": [0.0, 0.02, 0.0, 3.5],
        },
    }));
    let face = gltf.add_mesh("Face", &[(&head(), Some(face_material))]);
    let hair = gltf.add_mesh("Hair", &[(&hair_cap(), Some(hair_material))]);
    let face_node = gltf.add_node(json!({ "name": "Face", "mesh": face }));
    let hair_node = gltf.add_node(json!({ "name": "Hair", "mesh": hair }));
    let root = gltf.add_node(json!({ "name": "Head", "children": [face_node, hair_node] }));
    gltf.add_root(root);
    gltf.to_glb()
}

/// The head's surface: a UV sphere moved onto the head ([`head_point`]), with normals from the
/// moved surface and the front projection's UVs. Vertex color G thins its outline, as the
/// mannequin's head.
fn head() -> Geometry {
    let mut geometry = Geometry::default();
    let stride = SEGMENTS + 1;
    for ring in 0..=RINGS {
        let theta = PI * ring as f32 / RINGS as f32;
        for segment in 0..=SEGMENTS {
            let phi = TAU * segment as f32 / SEGMENTS as f32;
            let at = |theta: f32, phi: f32| {
                let s = [theta.sin() * phi.sin(), theta.cos(), theta.sin() * phi.cos()];
                head_point(s.map(|c| c * RADIUS))
            };
            let position = at(theta, phi);
            // The moved surface's normal from its tangents (at the poles, along the axis).
            let e = 1e-3;
            let d_theta = sub(at(theta + e, phi), at(theta - e, phi));
            let d_phi = sub(at(theta, phi + e), at(theta, phi - e));
            let mut normal = normalize(cross(d_theta, d_phi));
            if !normal.iter().all(|c| c.is_finite()) || theta < e || theta > PI - e {
                normal = [0.0, theta.cos().signum(), 0.0];
            }
            geometry.positions.push(position);
            geometry.normals.push(normal);
            geometry.uvs.push(uv(position[0], position[1]));
            geometry.colors.push([255, 150, 255, 255]);
        }
    }
    for ring in 0..RINGS {
        for segment in 0..SEGMENTS {
            let a = ring * stride + segment;
            let (b, c, d) = (a + stride, a + 1, a + stride + 1);
            // Counter-clockwise seen from outside.
            geometry.indices.extend([a, b, c, c, b, d]);
        }
    }
    geometry
}

/// The hair cap: the top of a slightly larger sphere, tipped back so the forehead shows from the
/// brows up, and down over the temples at the sides.
fn hair_cap() -> Geometry {
    const CAP_RINGS: u32 = 16;
    let radius = RADIUS * 1.08;
    let max_polar = 100f32.to_radians();
    let tip = -34f32.to_radians();
    let (sin, cos) = tip.sin_cos();
    let mut geometry = Geometry::default();
    let stride = SEGMENTS + 1;
    for ring in 0..=CAP_RINGS {
        let theta = max_polar * ring as f32 / CAP_RINGS as f32;
        for segment in 0..=SEGMENTS {
            let phi = TAU * segment as f32 / SEGMENTS as f32;
            let n = [theta.sin() * phi.sin(), theta.cos(), theta.sin() * phi.cos()];
            // Tipped back about X, and nudged up.
            let n = [n[0], n[1] * cos - n[2] * sin, n[1] * sin + n[2] * cos];
            geometry.positions.push([n[0] * radius, n[1] * radius + 0.004, n[2] * radius]);
            geometry.normals.push(n);
            geometry.uvs.push([segment as f32 / SEGMENTS as f32, ring as f32 / CAP_RINGS as f32]);
        }
    }
    for ring in 0..CAP_RINGS {
        for segment in 0..SEGMENTS {
            let a = ring * stride + segment;
            let (b, c, d) = (a + stride, a + 1, a + stride + 1);
            geometry.indices.extend([a, b, c, c, b, d]);
        }
    }
    geometry
}

fn sub(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    std::array::from_fn(|i| a[i] - b[i])
}

fn cross(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
}

fn normalize(v: [f32; 3]) -> [f32; 3] {
    let length = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    v.map(|c| c / length)
}

/// An 8-bit gray PNG [`SIZE`] square, each texel `value(u, v)` at its center.
fn gray_png(value: impl Fn(f32, f32) -> f32) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::GrayImage::from_fn(SIZE, SIZE, |x, y| {
        image::Luma([(value(center(x), center(y)).clamp(0.0, 1.0) * 255.0).round() as u8])
    });
    encode(image)
}

/// An 8-bit RGB PNG [`SIZE`] square, each texel `value(x, y)` at its center's head-local point.
fn rgb_png(value: impl Fn(f32, f32) -> [f32; 3]) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::RgbImage::from_fn(SIZE, SIZE, |x, y| {
        let (px, py) = point(center(x), center(y));
        image::Rgb(value(px, py).map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8))
    });
    encode(image)
}

fn encode<P: image::PixelWithColorType, C: std::ops::Deref<Target = [P::Subpixel]>>(
    image: image::ImageBuffer<P, C>,
) -> io::Result<Vec<u8>>
where
    [P::Subpixel]: image::EncodableLayout,
{
    let mut bytes = io::Cursor::new(Vec::new());
    image.write_to(&mut bytes, image::ImageFormat::Png).map_err(io::Error::other)?;
    Ok(bytes.into_inner())
}

