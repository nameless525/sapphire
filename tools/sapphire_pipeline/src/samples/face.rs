/// The bangs' hair mask (`character_maps::hair_mask`) at strand coordinates `(u, v)`: across the
/// strand, and from its root to its tip. R paints the highlight band across the strands, its
/// edges wavy as an artist's are; G tilts the band a little; B darkens the roots.
fn hair_mask(u: f32, v: f32) -> [f32; 3] {
    let texel = 1.0 / SIZE as f32;
    let top = 0.28 + 0.05 * (u * TAU).cos();
    let bottom = 0.55 + 0.05 * (u * 3.0 * PI).sin();
    let band = smoothstep(top - texel, top + texel, v) * smoothstep(bottom + texel, bottom - texel, v);
    let shift = 0.5 + 0.08 * (u - 0.5);
    let occlusion = (0.6 + 0.4 * smoothstep(0.0, 0.35, v)) * (0.85 + 0.15 * (PI * u).sin());
    [band, shift, occlusion]
}

fn hair_mask_png() -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::RgbImage::from_fn(SIZE, SIZE, |x, y| {
        image::Rgb(hair_mask(center(x), center(y)).map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8))
    });
    encode(image)
}

/// Rings and segments of the head's sphere.
const RINGS: u32 = 32;
const SEGMENTS: u32 = 48;

/// The head as a binary glTF: the face (slot [`FACE_SLOT`]), the hair cap ([`HAIR_SLOT`]), the
/// bangs ([`BANGS_SLOT`]) and the brows ([`BROWS_SLOT`]). The sidecar binds every slot to its
/// document; each embeds a flat material from the Blender extras the glTF importer reads, for an
/// import without them.
pub fn head_glb() -> Vec<u8> {
    let mut gltf = GltfWriter::default();
    let face_material = gltf.add_material(json!({
        "name": FACE_SLOT,
        "pbrMetallicRoughness": { "baseColorFactor": [1.0, 1.0, 1.0, 1.0] },
    }));
    let [hr, hg, hb] = HAIR_COLOR;
    let [or, og, ob] = HAIR_OUTLINE;
    let flat = |name: &str, color: [f32; 4], outline: f32| {
        json!({
            "name": name,
            "pbrMetallicRoughness": { "baseColorFactor": color },
            "extras": {
                // Flat: the same tone lit and in shadow.
                "shade_color": [1.0, 1.0, 1.0, 1.0],
                "outline_color": srgb8(or, og, ob),
                "character_shading": [0.0, 0.02, 0.0, outline],
            },
        })
    };
    let hair_material = gltf.add_material(flat(HAIR_SLOT, srgb8(hr, hg, hb), 3.5));
    let bangs_material = gltf.add_material(flat(BANGS_SLOT, srgb8(hr, hg, hb), 0.0));
    let brows_material = gltf.add_material(flat(BROWS_SLOT, srgb8(96, 58, 50), 0.0));
    let face = gltf.add_mesh("Face", &[(&head(), Some(face_material))]);
    let hair = gltf.add_mesh("Hair", &[(&hair_cap(), Some(hair_material))]);
    let fringe = gltf.add_mesh("Bangs", &[(&bangs(), Some(bangs_material))]);
    let arcs = gltf.add_mesh("Brows", &[(&brows(), Some(brows_material))]);
    let face_node = gltf.add_node(json!({ "name": "Face", "mesh": face }));
    let hair_node = gltf.add_node(json!({ "name": "Hair", "mesh": hair }));
    let bangs_node = gltf.add_node(json!({ "name": "Bangs", "mesh": fringe }));
    let brows_node = gltf.add_node(json!({ "name": "Brows", "mesh": arcs }));
    let root = gltf.add_node(json!({
        "name": "Head", "children": [face_node, hair_node, bangs_node, brows_node],
    }));
    gltf.add_root(root);
    gltf.to_glb()
}

/// The head's surface: a UV sphere moved onto the head ([`head_point`]), with normals from the
/// moved surface and the front projection's UVs. Vertex color G thins its outline, as the
/// mannequin's head.
fn head() -> Geometry {
    let mut geometry = Geometry::default();
    let stride = SEGMENTS + 1;
    for ring in 0..=RINGS {
        let theta = PI * ring as f32 / RINGS as f32;
        for segment in 0..=SEGMENTS {
            let phi = TAU * segment as f32 / SEGMENTS as f32;
            let at = |theta: f32, phi: f32| {
                let s = [theta.sin() * phi.sin(), theta.cos(), theta.sin() * phi.cos()];
                head_point(s.map(|c| c * RADIUS))
            };
            let position = at(theta, phi);
            // The moved surface's normal from its tangents (at the poles, along the axis).
            let e = 1e-3;
            let d_theta = sub(at(theta + e, phi), at(theta - e, phi));
            let d_phi = sub(at(theta, phi + e), at(theta, phi - e));
            let mut normal = normalize(cross(d_theta, d_phi));
            if !normal.iter().all(|c| c.is_finite()) || theta < e || theta > PI - e {
                normal = [0.0, theta.cos().signum(), 0.0];
            }
            geometry.positions.push(position);
            geometry.normals.push(normal);
            geometry.uvs.push(uv(position[0], position[1]));
            geometry.colors.push([255, 150, 255, 255]);
        }
    }
    for ring in 0..RINGS {
        for segment in 0..SEGMENTS {
            let a = ring * stride + segment;
            let (b, c, d) = (a + stride, a + 1, a + stride + 1);
            // Counter-clockwise seen from outside.
            geometry.indices.extend([a, b, c, c, b, d]);
        }
    }
    geometry
}

/// The hair cap: the top of a slightly larger sphere, tipped back so the forehead shows from the
/// brows up, and down over the temples at the sides.
fn hair_cap() -> Geometry {
    const CAP_RINGS: u32 = 16;
    let radius = RADIUS * 1.08;
    let max_polar = 100f32.to_radians();
    let tip = -34f32.to_radians();
    let (sin, cos) = tip.sin_cos();
    let mut geometry = Geometry::default();
    let stride = SEGMENTS + 1;
    for ring in 0..=CAP_RINGS {
        let theta = max_polar * ring as f32 / CAP_RINGS as f32;
        for segment in 0..=SEGMENTS {
            let phi = TAU * segment as f32 / SEGMENTS as f32;
            let n = [theta.sin() * phi.sin(), theta.cos(), theta.sin() * phi.cos()];
            // Tipped back about X, and nudged up.
            let n = [n[0], n[1] * cos - n[2] * sin, n[1] * sin + n[2] * cos];
            geometry.positions.push([n[0] * radius, n[1] * radius + 0.004, n[2] * radius]);
            geometry.normals.push(n);
            geometry.uvs.push([segment as f32 / SEGMENTS as f32, ring as f32 / CAP_RINGS as f32]);
        }
    }
    for ring in 0..CAP_RINGS {
        for segment in 0..SEGMENTS {
            let a = ring * stride + segment;
            let (b, c, d) = (a + stride, a + 1, a + stride + 1);
            geometry.indices.extend([a, b, c, c, b, d]);
        }
    }
    geometry
}

/// The bangs' sphere around the head's center, in meters: far enough off the forehead (about
/// 12 mm) that their shadow falls on it beside them rather than under them.
const BANGS_RADIUS: f32 = RADIUS * 1.1;
/// The strands: each one's angle around the head from the front toward its left (+X), and the
/// polar angle of its tip from the top, in degrees. Symmetric, the longest over the eyes.
const STRANDS: [(f32, f32); 9] = [
    (-48.0, 86.0),
    (-36.0, 90.0),
    (-24.0, 95.0),
    (-12.0, 91.0),
    (0.0, 87.0),
    (12.0, 91.0),
    (24.0, 95.0),
    (36.0, 90.0),
    (48.0, 86.0),
];
/// Where the strands start, in degrees from the top: under the cap's front edge.
const STRAND_ROOT: f32 = 50.0;
/// A strand's half-width at its root, in degrees around the head; it narrows to a point.
const STRAND_HALF_WIDTH: f32 = 5.8;
/// Rows of vertices along each strand.
const STRAND_ROWS: u32 = 12;

/// The bangs (M1 C5): [`STRANDS`] pointed strands on a sphere of [`BANGS_RADIUS`], from under the
/// cap down over the brows and the tops of the eyes, with gaps between them. Their normals are
/// the sphere's; their UVs run across each strand (`u`) and from its root to its tip (`v`), the
/// way the hair mask is painted and Kajiya-Kay's strands run.
fn bangs() -> Geometry {
    let mut geometry = Geometry::default();
    for (azimuth, tip) in STRANDS {
        let first = geometry.positions.len() as u32;
        for row in 0..=STRAND_ROWS {
            let v = row as f32 / STRAND_ROWS as f32;
            let theta = (STRAND_ROOT + (tip - STRAND_ROOT) * v).to_radians();
            // Pointed: narrowing faster toward the tip.
            let half = STRAND_HALF_WIDTH * (1.0 - v * v).max(0.02);
            for (column, offset) in [-half, 0.0, half].into_iter().enumerate() {
                let phi = (azimuth + offset).to_radians();
                let n = [theta.sin() * phi.sin(), theta.cos(), theta.sin() * phi.cos()];
                geometry.positions.push(n.map(|c| c * BANGS_RADIUS));
                geometry.normals.push(n);
                geometry.uvs.push([column as f32 * 0.5, v]);
            }
        }
        for row in 0..STRAND_ROWS {
            for column in 0..2 {
                let a = first + row * 3 + column;
                let (b, c, d) = (a + 3, a + 1, a + 4);
                // Counter-clockwise seen from outside: rows run down, columns toward +X.
                geometry.indices.extend([a, b, c, c, b, d]);
            }
        }
    }
    geometry
}

/// The brows' arcs (M1 C5), in head-local front coordinates: centered at `(±0.045, 0.012)`, the
/// top of an ellipse of these radii, a band this thick, spanning this many radians either side
/// of its top.
const BROW_CENTER: (f32, f32) = (0.045, 0.012);
const BROW_RADII: (f32, f32) = (0.03, 0.026);
const BROW_THICKNESS: f32 = 0.004;
const BROW_SPAN: f32 = 0.95;
/// How far off the face the brows sit, in meters.
const BROW_LIFT: f32 = 0.0015;
/// Vertices along each brow.
const BROW_STEPS: u32 = 16;

/// The brows (M1 C5): two arcs above the eyes, thinning toward their ends, a little off the face
/// along its normal, with the face's front-projected UVs. Mirror images of each other.
fn brows() -> Geometry {
    let mut geometry = Geometry::default();
    for side in [-1.0f32, 1.0] {
        let first = geometry.positions.len() as u32;
        for step in 0..=BROW_STEPS {
            let t = BROW_SPAN * (2.0 * step as f32 / BROW_STEPS as f32 - 1.0);
            let thickness = BROW_THICKNESS * (1.0 - 0.6 * (t / BROW_SPAN).powi(2));
            let x = side * (BROW_CENTER.0 + BROW_RADII.0 * t.sin());
            for edge in [0.0, -thickness] {
                let y = BROW_CENTER.1 + BROW_RADII.1 * t.cos() + edge;
                let [sx, sy, sz] = sphere_point(x, y).expect("the brows lie on the face");
                let n = normalize([sx, sy, sz]);
                let lift = RADIUS + BROW_LIFT;
                geometry.positions.push(head_point([n[0] * lift, n[1] * lift, n[2] * lift]));
                geometry.normals.push(n);
                geometry.uvs.push(uv(x, y));
            }
        }
        for step in 0..BROW_STEPS {
            let a = first + 2 * step;
            let (b, c, d) = (a + 1, a + 2, a + 3);
            // Counter-clockwise seen from the front: the arc runs toward +X on the right brow
            // (x > 0) and toward −X, mirrored, on the left.
            if side > 0.0 {
                geometry.indices.extend([a, b, c, c, b, d]);
            } else {
                geometry.indices.extend([a, c, b, c, d, b]);
            }
        }
    }
    geometry
}

fn sub(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    std::array::from_fn(|i| a[i] - b[i])
}

fn cross(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
}

fn normalize(v: [f32; 3]) -> [f32; 3] {
    let length = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    v.map(|c| c / length)
}

/// An 8-bit gray PNG [`SIZE`] square, each texel `value(u, v)` at its center.
fn gray_png(value: impl Fn(f32, f32) -> f32) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::GrayImage::from_fn(SIZE, SIZE, |x, y| {
        image::Luma([(value(center(x), center(y)).clamp(0.0, 1.0) * 255.0).round() as u8])
    });
    encode(image)
}

/// An 8-bit RGB PNG [`SIZE`] square, each texel `value(x, y)` at its center's head-local point.
fn rgb_png(value: impl Fn(f32, f32) -> [f32; 3]) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::RgbImage::from_fn(SIZE, SIZE, |x, y| {
        let (px, py) = point(center(x), center(y));
        image::Rgb(value(px, py).map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8))
    });
    encode(image)
}

fn encode<P: image::PixelWithColorType, C: std::ops::Deref<Target = [P::Subpixel]>>(
    image: image::ImageBuffer<P, C>,
) -> io::Result<Vec<u8>>
where
    [P::Subpixel]: image::EncodableLayout,
{
    let mut bytes = io::Cursor::new(Vec::new());
    image.write_to(&mut bytes, image::ImageFormat::Png).map_err(io::Error::other)?;
    Ok(bytes.into_inner())
}

