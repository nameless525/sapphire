    #[test]
    fn the_face_map_generates_and_turns_where_the_fields_say() {
        let dir = TempDir::new("face_sdf");
        for (name, bytes) in files().unwrap() {
            let path = dir.path().join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, bytes).unwrap();
        }
        let document = dir.path().join(DIR).join(SDF_FILE_NAME);
        let text = std::fs::read(&document).unwrap();
        let map = generate(&document, &text, &MapKind::FaceSdf.default_settings()).expect("monotonic masks");
        assert_eq!((map.image.width, map.image.height), (SIZE, SIZE));
        let texel = |u: f32, v: f32| {
            let (x, y) = ((u * SIZE as f32) as u32, (v * SIZE as f32) as u32);
            map.image.pixels[(y * SIZE + x) as usize]
        };
        // At a mask's angle the map reproduces the mask; between masks, the field within a mask
        // step.
        let mut checked = 0;
        for v in (8..SIZE).step_by(13).map(|i| (i as f32 + 0.5) / SIZE as f32) {
            for u in (8..SIZE).step_by(11).map(|i| (i as f32 + 0.5) / SIZE as f32) {
                let (x, y) = point(u, v);
                // Gray + alpha: the generator writes the two channels as A2's SDF class reads them.
                let [r, _, _, g] = texel(u, v);
                match (horizontal_threshold(x, y), vertical_threshold(x, y)) {
                    (Some(h), Some(vertical)) => {
                        assert!((r * 180.0 - h).abs() <= 10.0, "R at ({u}, {v}): {} for {h}", r * 180.0);
                        assert!(
                            (g * 180.0 - vertical.min(180.0)).abs() <= 15.0 || vertical > 90.0,
                            "G at ({u}, {v}): {} for {vertical}",
                            g * 180.0
                        );
                        assert!(face_sdf::is_lit(r, 0.0) && face_sdf::is_lit(g, 0.0), "lit from the front");
                        checked += 1;
                    }
                    _ => assert_eq!([r, g], [0.0, 0.0], "outside the head: never lit"),
                }
            }
        }
        assert!(checked > 200, "{checked} texels on the face");
    }

    #[test]
    fn the_fields_have_the_faces_shapes() {
        // A sphere's terminator: the near side lit longest, the far side least.
        let h = |x, y| horizontal_threshold(x, y).expect("on the face");
        assert!(h(-0.11, 0.0) > 150.0 && h(0.11, 0.0) < 40.0 && (h(0.0, 0.03) - 90.0).abs() < 1.0);
        // The nose shadow on the far side of the nose, and the cheek that stays lit.
        assert_eq!(h(0.006, -0.048), 38.0);
        assert!(h(0.04, -0.045) > h(0.04, 0.03) + 10.0, "the far cheek outlasts the temple");
        // A top light: the forehead lit longest, the sockets and under the nose dark early.
        let v = |x, y| vertical_threshold(x, y).expect("on the face");
        assert!(v(0.0, 0.08) > 110.0 && v(0.04, 0.01) == 52.0 && v(0.003, -0.06) == 34.0);
        assert!(v(0.0, -0.13) < 60.0, "the chin");
        // Mirror-symmetric where the shapes are: the vertical field is.
        assert_eq!(v(-0.04, 0.01), v(0.04, 0.01));
        assert_eq!(horizontal_threshold(0.2, 0.0), None, "outside the head");
    }

    #[test]
    fn the_head_is_symmetric_and_its_uvs_project_the_front() {
        let head = head();
        for (position, uv_at) in head.positions.iter().zip(&head.uvs) {
            assert_eq!(*uv_at, uv(position[0], position[1]));
            assert!((0.0..=1.0).contains(&uv_at[0]) && (0.0..=1.0).contains(&uv_at[1]), "{uv_at:?}");
        }
        // Every point has a mirror image, about x = 0, with the mirrored u.
        let mirrored = |p: [f32; 3]| {
            head.positions.iter().any(|q| {
                (q[0] + p[0]).abs() < 1e-5 && (q[1] - p[1]).abs() < 1e-5 && (q[2] - p[2]).abs() < 1e-5
            })
        };
        assert!(head.positions.iter().all(|&p| mirrored(p)));
        // Normals face out of the head.
        for (p, n) in head.positions.iter().zip(&head.normals) {
            let out = p[0] * n[0] + p[1] * n[1] + p[2] * n[2];
            assert!(
                out > 0.0 && ((n[0] * n[0] + n[1] * n[1] + n[2] * n[2]) - 1.0).abs() < 1e-3,
                "{p:?} {n:?}"
            );
        }
        let chin = head.positions.iter().map(|p| p[1]).fold(f32::INFINITY, f32::min);
        assert!((chin + RADIUS * JAW_STRETCH).abs() < 1e-4, "the jaw is drawn out: {chin}");
    }

