use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use sapphire_assets::sound::decode_vorbis;

use super::*;

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn specs_dir() -> PathBuf {
    repo().join("tools/sounds")
}

/// Every committed spec's file, made.
fn generated() -> Vec<Generated> {
    read_all(&specs_dir()).unwrap().iter().map(|(_, sound)| generate(sound)).collect()
}

/// The committed sounds were made here: macOS on arm64. CI's macOS runners are too.
fn made_here() -> bool {
    (std::env::consts::OS, std::env::consts::ARCH) == ("macos", "aarch64")
}

/// Every committed file is what its spec makes. Where they were made it's held to the byte, which is
/// what kept M3's nine files as they were when their constants became specs (M4 R4). Elsewhere `std`'s
/// math and libvorbis's build can differ in the last bits, so the decoded sounds are held to each
/// other within what the codec's own quantization moves, and the line this writes to stderr says
/// whether the bytes agreed. Regenerate with `cargo run -p sapphire_soundgen -- --force` from the
/// workspace root, on macOS on arm64.
#[test]
fn the_committed_sounds_are_generated() {
    let content = repo().join("content");
    let files = generated();
    assert!(files.len() >= 9, "only {} specs", files.len());
    for mut file in files {
        let bytes = file.encode().unwrap();
        let committed = fs::read(content.join(&file.path))
            .unwrap_or_else(|error| panic!("{}: {error}; write it with sapphire_soundgen", file.path));
        let line = format!(
            "soundgen-digest {} arch={} os={} same_bytes={}\n",
            file.path,
            std::env::consts::ARCH,
            std::env::consts::OS,
            committed == bytes
        );
        // Not `eprint!`: the harness captures that from a test that passes.
        std::io::stderr().write_all(line.as_bytes()).unwrap();
        if committed == bytes {
            continue;
        }
        assert!(!made_here(), "{}: the generated bytes differ from the committed ones", file.path);
        let (ours, theirs) = (decode_vorbis(&bytes).unwrap(), decode_vorbis(&committed).unwrap());
        assert_eq!(ours.frames(), theirs.frames(), "{}", file.path);
        let error = apart(&ours.samples, &theirs.samples);
        assert!(error < SAME_SOUND, "{}: the decoded sounds are {error} apart", file.path);
    }
}

/// How far two encodings of one sound, its samples a few bits apart, may decode from each other, by
/// [`apart`]: ten times the most the next test measured (0.0053, `en/perfect-dodge`, on macOS on arm64).
const SAME_SOUND: f32 = 0.05;

/// How far `theirs` is from `ours`: the difference's RMS over the sound's. A codec's choices flip a
/// sample here and there where the samples barely moved, which a largest difference would make much of.
fn apart(ours: &[f32], theirs: &[f32]) -> f32 {
    let difference: f64 = ours.iter().zip(theirs).map(|(a, b)| f64::from(a - b).powi(2)).sum();
    let sound: f64 = ours.iter().map(|a| f64::from(*a).powi(2)).sum();
    (difference / sound).sqrt() as f32
}

/// What [`SAME_SOUND`] allows for: every sound with every third sample an ulp nearer zero, as another
/// machine's `sin` or `exp` might leave it, decodes within it of the sound as made.
#[test]
fn a_sound_a_few_bits_off_decodes_as_the_same_sound() {
    let mut most = 0.0_f32;
    for mut file in generated() {
        let bytes = file.encode().unwrap();
        let mut nudged =
            Generated { path: file.path.clone(), samples: file.samples.clone(), looped: file.looped };
        for sample in nudged.samples.iter_mut().step_by(3).filter(|sample| **sample != 0.0) {
            *sample = f32::from_bits(sample.to_bits() - 1);
        }
        let other = encode(&nudged.samples, serial_of(&nudged.path)).unwrap();
        let (ours, theirs) = (decode_vorbis(&bytes).unwrap(), decode_vorbis(&other).unwrap());
        let error = apart(&ours.samples, &theirs.samples);
        eprintln!("{}: {} bytes alike: {}, decoded {error} apart", file.path, bytes.len(), bytes == other);
        most = most.max(error);
    }
    assert!(most < SAME_SOUND, "{most}");
}

/// ... and isn't so loose a changed note passes: the bells' third note a tone up (P0's spike) is far
/// past it.
#[test]
fn a_changed_note_is_not_the_same_sound() {
    let (_, mut sound) = read_all(&specs_dir())
        .unwrap()
        .into_iter()
        .find(|(path, _)| path.ends_with("lantern_bells.sound.ron"))
        .unwrap();
    let mut file = generate(&sound);
    let Synth::Stem(Stem { part: Part::Bells(bells), .. }) = &mut sound.sound else { panic!("not bells") };
    bells.tune[2] = Some(81);
    let mut changed = generate(&sound);
    let (ours, theirs) = (file.encode().unwrap(), changed.encode().unwrap());
    let error = apart(&decode_vorbis(&ours).unwrap().samples, &decode_vorbis(&theirs).unwrap().samples);
    assert!(error > 4.0 * SAME_SOUND, "{error}");
}

#[test]
fn every_file_comes_out_the_same_twice_and_as_long_as_it_must_be() {
    for ((_, sound), mut twin) in read_all(&specs_dir()).unwrap().iter().zip(generated()) {
        let mut file = generate(sound);
        let bytes = file.encode().unwrap();
        assert_eq!(bytes, twin.encode().unwrap(), "{}", file.path);
        let decoded = decode_vorbis(&bytes).unwrap();
        assert_eq!((decoded.sample_rate, decoded.channels), (SAMPLE_RATE, 1), "{}", file.path);
        // What the cook holds a stem to: the loop, to the frame.
        assert_eq!(decoded.frames(), file.samples.len(), "{}", file.path);
        if let Synth::Stem(stem) = &sound.sound {
            let seconds = f64::from(stem.beats_per_bar * stem.bars) * 60.0 / stem.tempo_bpm;
            assert_eq!(file.samples.len() as f64, seconds * f64::from(SAMPLE_RATE), "{}", file.path);
        }
    }
}

#[test]
fn the_languages_lines_differ_and_none_is_silent() {
    let files = generated();
    let line = |path: &str| &files.iter().find(|file| file.path.ends_with(path)).unwrap().samples;
    for path in ["en/perfect-dodge.ogg", "ja/perfect-dodge.ogg", "en/swap-in.ogg", "ja/swap-in.ogg"] {
        let peak = line(path).iter().fold(0.0_f32, |peak, sample| peak.max(sample.abs()));
        assert!((peak - PEAK).abs() < 1e-6, "{path}: {peak}");
    }
    assert_ne!(line("en/perfect-dodge.ogg").len(), line("ja/perfect-dodge.ogg").len());
}

#[test]
fn a_stem_loops_with_no_step_at_its_seam() {
    // What rings past the end came round to the start: the last sample and the first are close, as
    // any two neighbours are.
    for file in generated().iter().filter(|file| file.looped) {
        let steps = file.samples.windows(2).map(|pair| (pair[1] - pair[0]).abs());
        let largest = steps.fold(0.0_f32, f32::max);
        let seam = (file.samples[0] - file.samples[file.samples.len() - 1]).abs();
        assert!(seam <= largest, "{}: the seam steps {seam}, more than anywhere else ({largest})", file.path);
    }
}

/// Every sound is the project's own work, and says so: the nearest `SOURCE.md` above it under the
/// content directory names it (m1-plan §3).
#[test]
fn every_sound_is_in_its_source_md() {
    let content = repo().join("content");
    for file in generated() {
        let mut folder = Path::new(&file.path).parent();
        let source = loop {
            let dir = folder.unwrap_or_else(|| panic!("{}: no SOURCE.md above it", file.path));
            let source = content.join(dir).join("SOURCE.md");
            if source.exists() {
                break (dir, fs::read_to_string(source).unwrap());
            }
            folder = dir.parent();
        };
        let named =
            Path::new(&file.path).strip_prefix(source.0).unwrap().to_str().unwrap().replace('\\', "/");
        assert!(
            source.1.contains(&format!("`{named}`")),
            "{}: {}/SOURCE.md doesn't name `{named}`",
            file.path,
            source.0.display()
        );
    }
}

/// A spec, in a folder of its own under the system's temporary one.
fn scratch_spec(name: &str, data: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("sapphire_soundgen-{}-{name}", std::process::id()));
    fs::create_dir_all(&dir).unwrap();
    let path = dir.join(format!("{name}{SPEC_EXTENSION}"));
    fs::write(&path, format!("(type: \"sapphire::soundgen::Sound\", version: 1, data: ({data}))")).unwrap();
    path
}

const STEM: &str = "tempo_bpm: 120.0, beats_per_bar: 4, bars: 4";
const PAD: &str = "Pad((chords: [[57], [53], [60], [55]]))";

fn stem(part: &str) -> String {
    format!("path: \"audio/test.ogg\", sound: Stem(({STEM}, part: {part}))")
}

fn line(syllables: &str, rest: &str) -> String {
    format!("path: \"audio/test.ogg\", sound: Line((speaker_hz: 230.0, syllables: [{syllables}], {rest}))")
}

/// The error reading a spec of `data` gives, with the file it named.
fn refused(name: &str, data: &str) -> (String, String) {
    let path = scratch_spec(name, data);
    let error = spec::read(&path).unwrap_err().to_string();
    fs::remove_dir_all(path.parent().unwrap()).unwrap();
    (error, path.display().to_string())
}

#[test]
fn a_spec_that_reads_is_one_the_generator_can_make() {
    let path = scratch_spec("good", &stem(PAD));
    let sound = spec::read(&path).unwrap();
    fs::remove_dir_all(path.parent().unwrap()).unwrap();
    let file = generate(&sound);
    assert_eq!(file.samples.len(), 192_000);
    assert!(file.looped);
}

#[test]
fn a_bad_spec_names_its_file_and_field() {
    let syllable = "(vowel: A, seconds: 0.1, pitch: 1.0, burst: true)";
    let cases = [
        // Unknown fields, at each depth.
        ("unknown", format!("path: \"audio/test.ogg\", loudness: 1.0, sound: Stem(({STEM}, part: {PAD}))"), "loudness"),
        ("unknown_stem", format!("path: \"audio/test.ogg\", sound: Stem(({STEM}, swing: 0.1, part: {PAD}))"), "swing"),
        ("unknown_part", stem("Pulse((notes: [33, 29, 36, 31], per_beat: 2, accent: 0.5))"), "accent"),
        ("unknown_syllable", line("(vowel: A, seconds: 0.1, pitch: 1.0, burst: true, breath: 0.2)", "seed: 1"), "breath"),
        ("unknown_part_kind", stem("Strings((notes: [1]))"), "Strings"),
        ("unknown_vowel", line("(vowel: Y, seconds: 0.1, pitch: 1.0, burst: true)", "seed: 1"), "Y"),
        // Values that can't be played.
        ("path", "path: \"../audio/test.ogg\", sound: Stem((tempo_bpm: 120.0, beats_per_bar: 4, bars: 4, part: Pad((chords: [[1], [1], [1], [1]]))))".to_owned(), "`path`"),
        ("not_ogg", format!("path: \"audio/test.wav\", sound: Stem(({STEM}, part: {PAD}))"), "`path`"),
        ("tempo", format!("path: \"audio/test.ogg\", sound: Stem((tempo_bpm: 7.0, beats_per_bar: 4, bars: 4, part: {PAD}))"), "`sound.tempo_bpm`"),
        ("tempo_frames", format!("path: \"audio/test.ogg\", sound: Stem((tempo_bpm: 97.0, beats_per_bar: 4, bars: 4, part: {PAD}))"), "`sound.tempo_bpm`"),
        ("beats", format!("path: \"audio/test.ogg\", sound: Stem((tempo_bpm: 120.0, beats_per_bar: 0, bars: 4, part: {PAD}))"), "`sound.beats_per_bar`"),
        ("bars", format!("path: \"audio/test.ogg\", sound: Stem((tempo_bpm: 120.0, beats_per_bar: 4, bars: 65, part: {PAD}))"), "`sound.bars`"),
        ("chords", stem("Pad((chords: [[57], [53], [60]]))"), "`sound.part.chords`"),
        ("empty_chord", stem("Pad((chords: [[57], [], [60], [55]]))"), "`sound.part.chords[1]`"),
        ("note", stem("Pad((chords: [[57], [53], [160], [55]]))"), "`sound.part.chords[2]`"),
        ("per_beat", stem("Pulse((notes: [33, 29, 36, 31], per_beat: 0))"), "`sound.part.per_beat`"),
        ("kick", stem("Drums((kick: [0.0, 4.0], snare: [], hats_per_beat: 2, seed: 1))"), "`sound.part.kick[1]`"),
        ("seed", stem("Drums((kick: [0.0], snare: [], hats_per_beat: 2, seed: 0))"), "`sound.part.seed`"),
        ("tune", stem("Bells((tune: [Some(76), None]))"), "`sound.part.tune`"),
        ("toll", stem("Toll((notes: [45, 41, 48, 200]))"), "`sound.part.notes`"),
        ("speaker", format!("path: \"audio/test.ogg\", sound: Line((speaker_hz: 0.0, syllables: [{syllable}], seed: 1))"), "`sound.speaker_hz`"),
        ("syllables", line("", "seed: 1"), "`sound.syllables`"),
        ("seconds", line(&format!("{syllable}, (vowel: O, seconds: -0.1, pitch: 1.0, burst: false)"), "seed: 1"), "`sound.syllables[1].seconds`"),
        ("pitch", line("(vowel: O, seconds: 0.1, pitch: 9.0, burst: false)", "seed: 1"), "`sound.syllables[0].pitch`"),
        ("line_seed", line(syllable, "seed: 0"), "`sound.seed`"),
    ];
    for (name, data, field) in cases {
        let (error, path) = refused(name, &data);
        assert!(error.contains(&path) && error.contains(field), "{name}: {error}");
    }
}

#[test]
fn two_specs_writing_one_file_is_an_error_naming_both() {
    let first = scratch_spec("twice", &stem(PAD));
    let dir = first.parent().unwrap().to_owned();
    fs::copy(&first, dir.join(format!("again{SPEC_EXTENSION}"))).unwrap();
    let error = read_all(&dir).unwrap_err().to_string();
    fs::remove_dir_all(&dir).unwrap();
    assert!(error.contains("again.sound.ron") && error.contains("twice.sound.ron"), "{error}");
}
