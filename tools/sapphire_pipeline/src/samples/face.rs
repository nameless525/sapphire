/// The head's sphere, in meters.
pub const RADIUS: f32 = 0.12;
/// Below the head's center, the sphere is drawn out by this much in Y and narrowed toward the
/// chin by up to this much in X, and less in Z: a jaw.
const JAW_STRETCH: f32 = 1.25;
const JAW_TAPER: f32 = 0.35;
const JAW_FLATTEN: f32 = 0.15;
/// How much of the sphere's elevation the vertical field keeps: an anime face's front is
/// flatter than a sphere, so a top light reaches lower before the face turns dark.
const FACE_FLATNESS: f32 = 0.65;
/// The front projection: meters per UV unit, and the `v` of the head's center.
const UV_SPAN: f32 = 0.3;
const UV_CENTER_V: f32 = 0.45;

/// Maps' size in texels.
const SIZE: u32 = 256;
/// The masks' angles, in degrees: horizontal every 10° from the front to behind, vertical every
/// 15° from the front to overhead.
const HORIZONTAL_ANGLES: [u32; 19] = {
    let mut angles = [0; 19];
    let mut i = 0;
    while i < 19 {
        angles[i] = 10 * i as u32;
        i += 1;
    }
    angles
};
const VERTICAL_ANGLES: [u32; 7] = [0, 15, 30, 45, 60, 75, 90];

