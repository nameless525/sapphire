/// The eye's outline (M1 C6): its corners' heights, in [`EYE_HALF`]'s height above
/// [`EYE_CENTER`] (the outer corner raised, as an anime eye's), and the shape of its upper and
/// lower arcs between them: how high each rises at the middle (the two together span the eye's
/// height) and how full it is, a power of `1 - s²` (below a half, a broad lid with pointed
/// corners).
const EYE_CORNERS: (f32, f32) = (-0.05, 0.3);
const EYE_ARCS: ((f32, f32), (f32, f32)) = ((0.875, 0.4), (1.125, 0.6));

/// The line between the eye's corners at `s`, from its inner corner (-1) to its outer (1), in
/// head-local y.
fn eye_middle(s: f32) -> f32 {
    let (inner, outer) = EYE_CORNERS;
    EYE_CENTER.1 + EYE_HALF.1 * (inner + (outer - inner) * 0.5 * (1.0 + s))
}

/// The eye's top and bottom outline at `s`, in head-local y.
fn eye_top(s: f32) -> f32 {
    let (rise, fullness) = EYE_ARCS.0;
    eye_middle(s) + EYE_HALF.1 * rise * (1.0 - s * s).max(0.0).powf(fullness)
}

fn eye_bottom(s: f32) -> f32 {
    let (fall, fullness) = EYE_ARCS.1;
    eye_middle(s) - EYE_HALF.1 * fall * (1.0 - s * s).max(0.0).powf(fullness)
}

/// The unit normal, outward from the eye, of the outline `curve` (in eye-local coordinates, x
/// outward from the eye's center) at `s = -cos(phi)`, from its tangent toward the outer corner:
/// up off the upper arc (`upper`), down off the lower.
fn outline_normal(curve: impl Fn(f32) -> (f32, f32), phi: f32, upper: bool) -> (f32, f32) {
    let e = 1e-3;
    // At the corners, from just inside them: the curve turns back on itself there.
    let phi = phi.clamp(2.0 * e, PI - 2.0 * e);
    let (a, b) = (curve(-(phi - e).cos()), curve(-(phi + e).cos()));
    let (tx, ty) = normalize2((b.0 - a.0, b.1 - a.1));
    if upper { (-ty, tx) } else { (ty, -tx) }
}

/// Head-local x at `s` across the eye on `side` (1 the head's left, +X; -1 its right), `widen`
/// times as wide as the eye.
fn eye_x(s: f32, side: f32, widen: f32) -> f32 {
    side * (EYE_CENTER.0 + s * widen * EYE_HALF.0)
}

/// `s` for column `t` (0 to 1) of an eye on `side`, columns running toward +X: denser toward the
/// corners, where the outline turns.
fn eye_column(t: f32, side: f32) -> f32 {
    side * (PI * (t - 0.5)).sin()
}

/// The lids' lower edge over `s` (clamped to the eye), `closed` of the way shut.
fn lid_edge(s: f32, closed: f32) -> f32 {
    let s = s.clamp(-1.0, 1.0);
    let open = eye_top(s) + LID_OPEN_GAP;
    let shut = eye_bottom(s) - LID_CLOSED_OVERLAP;
    open + (shut - open) * closed
}

/// The point `lift` meters off the head's surface (its sphere, moved onto the head as
/// [`head_point`] moves it) over head-local front point `(x, y)`, and the moved surface's normal.
fn on_face(x: f32, y: f32, lift: f32) -> ([f32; 3], [f32; 3]) {
    let n = normalize(sphere_point(x, y).expect("the eyes lie on the face"));
    let at = |n: [f32; 3]| head_point(n.map(|c| c * (RADIUS + lift)));
    let across = normalize(cross([0.0, 1.0, 0.0], n));
    let up = cross(n, across);
    let e = 1e-3;
    let toward = |t: [f32; 3], k: f32| at(normalize(std::array::from_fn(|i| n[i] + k * t[i])));
    let normal =
        normalize(cross(sub(toward(across, e), toward(across, -e)), sub(toward(up, e), toward(up, -e))));
    (at(n), normal)
}

/// How a vertex of the eyes moves under [`MORPH_TARGETS`] (M1 C6): with the lids (over `s`,
/// following their lower edge by `follow`), with the gaze, or not at all.
#[derive(Clone, Copy, Debug)]
enum Motion {
    Still,
    Lids { s: f32, follow: f32 },
    Gaze,
}

/// One layer of the eyes being built: its geometry, with a morph target per [`MORPH_TARGETS`].
struct EyeLayerBuilder {
    lift: f32,
    geometry: Geometry,
}

impl EyeLayerBuilder {
    fn new(lift: f32) -> Self {
        let geometry =
            Geometry { targets: vec![Default::default(); MORPH_TARGETS.len()], ..Geometry::default() };
        Self { lift, geometry }
    }

    /// Adds the vertex over head-local front point `(x, y)` at texture coordinate `uv`, moving
    /// by `motion`, and returns its index.
    fn vertex(&mut self, (x, y): (f32, f32), uv: [f32; 2], motion: Motion) -> u32 {
        let (position, normal) = on_face(x, y, self.lift);
        let index = self.geometry.positions.len() as u32;
        self.geometry.positions.push(position);
        self.geometry.normals.push(normal);
        self.geometry.uvs.push(uv);
        let lids = |closed: f32| match motion {
            Motion::Lids { s, follow } => (x, y + follow * (lid_edge(s, closed) - lid_edge(s, 0.0))),
            _ => (x, y),
        };
        let look = |dx: f32, dy: f32| match motion {
            Motion::Gaze => (x + dx, y + dy),
            _ => (x, y),
        };
        // Each target from the pose it applies over: the lids' second step over their first.
        let poses = [
            ((x, y), lids(0.5)),
            (lids(0.5), lids(1.0)),
            ((x, y), look(LOOK.0, 0.0)),
            ((x, y), look(-LOOK.0, 0.0)),
            ((x, y), look(0.0, LOOK.1)),
            ((x, y), look(0.0, -LOOK.1)),
        ];
        for (target, (from, to)) in self.geometry.targets.iter_mut().zip(poses) {
            let (p0, n0) = on_face(from.0, from.1, self.lift);
            let (p1, n1) = on_face(to.0, to.1, self.lift);
            target.positions.push(sub(p1, p0));
            target.normals.push(sub(n1, n0));
        }
        index
    }

    /// Triangles over a grid of `columns` × `rows` vertices from `first`, row by row, columns
    /// toward +X and rows downward: counter-clockwise seen from the front.
    fn grid(&mut self, first: u32, columns: u32, rows: u32) {
        for row in 0..rows - 1 {
            for column in 0..columns - 1 {
                let a = first + row * columns + column;
                let (b, c, d) = (a + columns, a + 1, a + columns + 1);
                self.geometry.indices.extend([a, b, c, c, b, d]);
            }
        }
    }

    /// Appends `other`'s geometry, drawn with the same material.
    fn append(&mut self, other: Geometry) {
        let base = self.geometry.positions.len() as u32;
        self.geometry.positions.extend(other.positions);
        self.geometry.normals.extend(other.normals);
        self.geometry.uvs.extend(other.uvs);
        self.geometry.indices.extend(other.indices.iter().map(|index| base + index));
        for (target, extra) in self.geometry.targets.iter_mut().zip(other.targets) {
            target.positions.extend(extra.positions);
            target.normals.extend(extra.normals);
        }
    }
}

/// The parameter of column `c` of `columns`, from 0 to 1.
fn step(c: u32, columns: u32) -> f32 {
    c as f32 / (columns - 1) as f32
}

fn normalize2((x, y): (f32, f32)) -> (f32, f32) {
    let length = x.hypot(y);
    (x / length, y / length)
}

/// One column of a lash line (M1 C6): its edge over the eye and its outer edge, in eye-local
/// front coordinates (x outward from the eye's center, y the head's), and the `s` whose lid edge
/// it rides.
struct LashColumn {
    inner: (f32, f32),
    outer: (f32, f32),
    s: f32,
}

/// The upper lash line's thickness at `phi` along it (M1 C6): thin at the inner corner, thickest
/// toward the outer.
fn lash_thickness(phi: f32) -> f32 {
    0.0003 + 0.0013 * smoothstep(0.0, 0.3 * PI, phi) + 0.003 * smoothstep(0.3 * PI, 0.95 * PI, phi)
}

/// The upper lash line (M1 C6), from the eye's inner corner round its top along the open lids'
/// edge to the outer corner. Its edges lie along the outline's normal: a little over the eye,
/// and out by its thickness ([`lash_thickness`]), so at the outer corner, where the outline
/// turns down, the line ends across it, reaching out past the corner.
fn upper_lash() -> Vec<LashColumn> {
    let hx = EYE_HALF.0;
    let edge = |s: f32| (s * hx, lid_edge(s, 0.0));
    (0..LASH_COLUMNS)
        .map(|k| {
            let phi = PI * step(k, LASH_COLUMNS);
            let s = -phi.cos();
            let (x, y) = (s * hx, lid_edge(s, 0.0));
            let n = outline_normal(edge, phi, true);
            let t = lash_thickness(phi);
            LashColumn {
                inner: (x - n.0 * LASH_OVERLAP, y - n.1 * LASH_OVERLAP),
                outer: (x + n.0 * t, y + n.1 * t),
                s,
            }
        })
        .collect()
}

/// The upper lash line's wing (M1 C6): a flick out of the line's end, which reaches across the
/// outer corner, rising outward and thinning to a point. Its lower edge starts level with the
/// end, a quarter of the end's reach in from its tip, [`WING_WIDTH`] below its upper edge, and
/// runs [`WING_LENGTH`] out and [`WING_RISE`] up. A strip of its own, straight, so its edges
/// never cross, however sharply the line turns into it.
fn lash_wing() -> Vec<LashColumn> {
    let corner = (EYE_HALF.0, lid_edge(1.0, 0.0));
    let base = (corner.0 + 0.75 * lash_thickness(PI), corner.1);
    let tip = (base.0 + WING_LENGTH, base.1 + WING_RISE);
    let along = normalize2((WING_LENGTH, WING_RISE));
    let up = (-along.1, along.0);
    let half = 0.5 * WING_WIDTH;
    let start = (base.0 + up.0 * half, base.1 + up.1 * half);
    (0..WING_COLUMNS)
        .map(|k| {
            let w = step(k, WING_COLUMNS);
            let (x, y) = (start.0 + (tip.0 - start.0) * w, start.1 + (tip.1 - start.1) * w);
            // Holding its width most of the way, then closing to 0.1 mm at the tip.
            let half = half * (1.0 - w).sqrt() + 0.0001 * w;
            LashColumn {
                inner: (x - up.0 * half, y - up.1 * half),
                outer: (x + up.0 * half, y + up.1 * half),
                s: 1.0,
            }
        })
        .collect()
}

/// The lower lash line (M1 C6): thin, under the outer part of the eye's bottom, along the
/// outline's normal, a little over the eye and out by its thickness.
fn lower_lash() -> Vec<LashColumn> {
    let hx = EYE_HALF.0;
    (0..LOWER_LASH_COLUMNS)
        .map(|k| {
            let f = step(k, LOWER_LASH_COLUMNS);
            let phi = PI * (0.45 + 0.52 * f);
            let s = -phi.cos();
            let (x, y) = (s * hx, eye_bottom(s));
            let n = outline_normal(|s| (s * hx, eye_bottom(s)), phi, false);
            let t = 0.0003 + 0.0006 * (PI * f).sin();
            LashColumn { inner: (x - n.0 * 0.0003, y - n.1 * 0.0003), outer: (x + n.0 * t, y + n.1 * t), s }
        })
        .collect()
}

/// The eyes' layers (M1 C6), in [`EYE_SLOTS`]' order: eye whites, the lids' shadow, irises,
/// highlights, lash lines and lids, each over both eyes.
fn eyes() -> [Geometry; 6] {
    let sides = [-1.0f32, 1.0];

    // The eye white and the lid's shadow over it: the outline's columns, rows from its top to its
    // bottom. The shadow slides with the lids, its coverage running down from the top.
    let mut white = EyeLayerBuilder::new(EYE_WHITE_LIFT);
    let mut shadow = EyeLayerBuilder::new(EYE_SHADOW_LIFT);
    for side in sides {
        let first = (white.geometry.positions.len() as u32, shadow.geometry.positions.len() as u32);
        for row in 0..EYE_ROWS {
            let r = step(row, EYE_ROWS);
            for c in 0..EYE_COLUMNS {
                let t = step(c, EYE_COLUMNS);
                let s = eye_column(t, side);
                let at = (eye_x(s, side, 1.0), eye_top(s) + (eye_bottom(s) - eye_top(s)) * r);
                white.vertex(at, [t, r], Motion::Still);
                shadow.vertex(at, [t, r], Motion::Lids { s, follow: 1.0 });
            }
        }
        white.grid(first.0, EYE_COLUMNS, EYE_ROWS);
        shadow.grid(first.1, EYE_COLUMNS, EYE_ROWS);
    }

    // The irises: their ellipse's bounding box, the texture filling it, moving with the gaze.
    let mut iris = EyeLayerBuilder::new(IRIS_LIFT);
    for side in sides {
        let first = iris.geometry.positions.len() as u32;
        let center = (side * (EYE_CENTER.0 + IRIS_OFFSET.0), EYE_CENTER.1 + IRIS_OFFSET.1);
        for row in 0..IRIS_STEPS {
            let v = step(row, IRIS_STEPS);
            for c in 0..IRIS_STEPS {
                let u = step(c, IRIS_STEPS);
                let at = (center.0 + (2.0 * u - 1.0) * IRIS_HALF.0, center.1 - (2.0 * v - 1.0) * IRIS_HALF.1);
                iris.vertex(at, [u, v], Motion::Gaze);
            }
        }
        iris.grid(first, IRIS_STEPS, IRIS_STEPS);
    }

    // The highlights: discs over each iris, moving with it.
    let mut highlights = EyeLayerBuilder::new(HIGHLIGHT_LIFT);
    for side in sides {
        let iris_center = (side * (EYE_CENTER.0 + IRIS_OFFSET.0), EYE_CENTER.1 + IRIS_OFFSET.1);
        for (offset, half) in HIGHLIGHTS {
            let center = (iris_center.0 + offset.0, iris_center.1 + offset.1);
            let middle = highlights.vertex(center, [0.5, 0.5], Motion::Gaze);
            for segment in 0..HIGHLIGHT_SEGMENTS {
                let (sin, cos) = (TAU * segment as f32 / HIGHLIGHT_SEGMENTS as f32).sin_cos();
                let at = (center.0 + half.0 * cos, center.1 + half.1 * sin);
                highlights.vertex(at, [0.5 + 0.5 * cos, 0.5 - 0.5 * sin], Motion::Gaze);
            }
            for segment in 0..HIGHLIGHT_SEGMENTS {
                let next = (segment + 1) % HIGHLIGHT_SEGMENTS;
                // Counter-clockwise seen from the front: the angle grows from +X toward +Y.
                highlights.geometry.indices.extend([middle, middle + 1 + segment, middle + 1 + next]);
            }
        }
    }

    // The lash lines: the upper along the lids' edge, closing with them; a thin lower one under
    // the eye's outer part. Rows run from the edge farther up (the outer edge above, the upper
    // line; the inner edge, the lower line) to the one below it, and columns toward +X: outward
    // on the head's left, inward on its right, whose columns are mirrored and reversed.
    let mut lashes = EyeLayerBuilder::new(LASH_LIFT);
    let mut lower = EyeLayerBuilder::new(LOWER_LASH_LIFT);
    for side in sides {
        let ordered = |mut columns: Vec<LashColumn>| {
            if side < 0.0 {
                columns.reverse();
            }
            columns
        };
        let head = |(x, y): (f32, f32)| (side * (EYE_CENTER.0 + x), y);
        // The line, then its wing, each a strip.
        for upper in [ordered(upper_lash()), ordered(lash_wing())] {
            let first = lashes.geometry.positions.len() as u32;
            let count = upper.len() as u32;
            for row in 0..2 {
                for (c, column) in upper.iter().enumerate() {
                    let at = if row == 0 { column.outer } else { column.inner };
                    let uv = [step(c as u32, count), row as f32];
                    lashes.vertex(head(at), uv, Motion::Lids { s: column.s, follow: 1.0 });
                }
            }
            lashes.grid(first, count, 2);
        }

        let below = ordered(lower_lash());
        let first = lower.geometry.positions.len() as u32;
        let count = below.len() as u32;
        for row in 0..2 {
            for (c, column) in below.iter().enumerate() {
                let at = if row == 0 { column.inner } else { column.outer };
                lower.vertex(head(at), [step(c as u32, count), row as f32], Motion::Still);
            }
        }
        lower.grid(first, count, 2);
    }
    // One lash material draws both lines.
    lashes.append(lower.geometry);

    // The lids: bands of skin above the eyes, a little wider, whose rows close down over them,
    // the lowest with the edge; textured as the face under them is, by the front projection.
    let mut lids = EyeLayerBuilder::new(LID_LIFT);
    for side in sides {
        let first = lids.geometry.positions.len() as u32;
        for row in 0..LID_ROWS {
            let follow = step(row, LID_ROWS);
            for c in 0..EYE_COLUMNS {
                let s = eye_column(step(c, EYE_COLUMNS), side);
                let top = eye_top(s) + LID_BAND;
                let at = (eye_x(s, side, LID_WIDEN), top + (lid_edge(s, 0.0) - top) * follow);
                lids.vertex(at, uv(at.0, at.1), Motion::Lids { s, follow });
            }
        }
        lids.grid(first, EYE_COLUMNS, LID_ROWS);
    }

    [white.geometry, shadow.geometry, iris.geometry, highlights.geometry, lashes.geometry, lids.geometry]
}

/// The eyes' maps' size in texels (M1 C6): about a tenth of a millimeter each across the iris.
const EYE_MAP_SIZE: u32 = 256;

/// The lid's shadow on the eye white (M1 C6), `eye_shadow.png`: white, its coverage strongest at
/// the eye's top (`v` = 0) and gone two fifths of the way down.
fn eye_shadow(_u: f32, v: f32) -> [f32; 4] {
    let alpha = 0.8 * (1.0 - smoothstep(0.0, 0.42, v)).powf(1.4);
    [1.0, 1.0, 1.0, alpha]
}

/// The iris (M1 C6), `iris.png`, in sRGB with coverage: filling the texture's ellipse, darker
/// toward the top under the lid, with fine fibers, a bright crescent low in it, the limbal ring
/// and a pupil a little below the middle.
fn iris(u: f32, v: f32) -> [f32; 4] {
    const TOP: [u8; 3] = [26, 36, 92];
    const BOTTOM: [u8; 3] = [84, 196, 214];
    const GLOW: [u8; 3] = [176, 246, 236];
    const RING: [u8; 3] = [18, 22, 56];
    const PUPIL: [u8; 3] = [14, 14, 36];
    let q = (2.0 * u - 1.0, 2.0 * v - 1.0);
    let d = q.0.hypot(q.1);
    let texel = 2.0 / EYE_MAP_SIZE as f32;
    let alpha = smoothstep(1.0, 1.0 - 2.0 * texel, d);
    let top = TOP.map(|c| f32::from(c) / 255.0);
    let mut color = layer(top, BOTTOM, smoothstep(-0.95, 0.9, q.1));
    // Fibers: a fine radial ripple through the iris's middle.
    let angle = q.1.atan2(q.0);
    let fibers = 0.5 + 0.5 * (angle * 23.0 + 2.0 * (angle * 5.0).sin()).sin();
    let band = smoothstep(0.3, 0.45, d) * smoothstep(0.88, 0.7, d);
    color = color.map(|c| c * (1.0 - 0.1 * band * fibers));
    let crescent = smoothstep(0.15, 0.6, q.1) * smoothstep(0.35, 0.5, d) * smoothstep(0.86, 0.7, d);
    color = layer(color, GLOW, 0.6 * crescent);
    color = layer(color, RING, 0.85 * smoothstep(0.76, 0.93, d));
    let pupil = (q.0 / 0.27).hypot((q.1 - 0.06) / 0.4);
    color = layer(color, PUPIL, smoothstep(1.0, 0.85, pupil));
    [color[0], color[1], color[2], alpha]
}

/// A highlight (M1 C6), `eye_highlight.png`: a white disc filling the texture, its edge crisp
/// but soft.
fn highlight(u: f32, v: f32) -> [f32; 4] {
    let d = (2.0 * u - 1.0).hypot(2.0 * v - 1.0);
    [1.0, 1.0, 1.0, smoothstep(1.0, 0.8, d)]
}

/// An 8-bit RGBA PNG [`EYE_MAP_SIZE`] square, each texel `value(u, v)` at its center: sRGB color
/// and coverage.
fn eye_map_png(value: fn(f32, f32) -> [f32; 4]) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / EYE_MAP_SIZE as f32;
    let image = image::RgbaImage::from_fn(EYE_MAP_SIZE, EYE_MAP_SIZE, |x, y| {
        image::Rgba(value(center(x), center(y)).map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8))
    });
    encode(image)
}

fn sub(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    std::array::from_fn(|i| a[i] - b[i])
}

fn cross(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
}

fn normalize(v: [f32; 3]) -> [f32; 3] {
    let length = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    v.map(|c| c / length)
}

/// An 8-bit gray PNG [`SIZE`] square, each texel `value(u, v)` at its center.
fn gray_png(value: impl Fn(f32, f32) -> f32) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::GrayImage::from_fn(SIZE, SIZE, |x, y| {
        image::Luma([(value(center(x), center(y)).clamp(0.0, 1.0) * 255.0).round() as u8])
    });
    encode(image)
}

/// An 8-bit RGB PNG [`SIZE`] square, each texel `value(x, y)` at its center's head-local point.
fn rgb_png(value: impl Fn(f32, f32) -> [f32; 3]) -> io::Result<Vec<u8>> {
    let center = |i: u32| (i as f32 + 0.5) / SIZE as f32;
    let image = image::RgbImage::from_fn(SIZE, SIZE, |x, y| {
        let (px, py) = point(center(x), center(y));
        image::Rgb(value(px, py).map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8))
    });
    encode(image)
}

fn encode<P: image::PixelWithColorType, C: std::ops::Deref<Target = [P::Subpixel]>>(
    image: image::ImageBuffer<P, C>,
) -> io::Result<Vec<u8>>
where
    [P::Subpixel]: image::EncodableLayout,
{
    let mut bytes = io::Cursor::new(Vec::new());
    image.write_to(&mut bytes, image::ImageFormat::Png).map_err(io::Error::other)?;
    Ok(bytes.into_inner())
}

