//! The face test head's content (M1 C3): an anime head as a glTF, its face material and the
//! maps that material reads, written as sources so they travel the import → bake → cook path an
//! artist's face does. No third-party art: every shape is painted here, in code.
//!
//! - **`face_head.glb`:** a head of [`RADIUS`], facing +Z with +Y up, its lower half drawn out
//!   and narrowed into a jaw. Material slot `Face` covers it all and is bound by its sidecar to
//!   `face.material.ron`. Its UVs are a front projection ([`uv`]), mirror-symmetric about
//!   `u = 0.5` as face maps need. Over it (M1 C5): slot `Hair`, a cap over the top and back,
//!   bound to `hair.material.ron`; slot `Bangs`, a fringe of pointed strands hanging from the
//!   cap's front edge over the brows and the tops of the eyes, a little off the forehead
//!   ([`bangs`]), bound to `bangs.material.ron`; and slot `Brows`, two arcs just off the face
//!   ([`brows`]), bound to `brow.material.ron`. Each slot also embeds a flat material, which an
//!   unbound import draws.
//! - **Layered eyes** (M1 C6, in the head's mesh, [`EYE_SLOTS`]): over each eye's outline, a
//!   little off the face and stacked in their drawing order, the eye white (`EyeWhite`,
//!   `eye_white.material.ron`, the eye layer), the lid's shadow on it (`EyeShadow`,
//!   `eye_shadow.material.ron` with **`eye_shadow.png`**), the iris (`Iris`, `iris.material.ron`
//!   with **`iris.png`**: a gradient darker at the top, a bright lower crescent, a pupil and a
//!   limbal ring, behind the cornea by the parallax fake) and two highlights (`EyeHighlight`,
//!   `eye_highlight.material.ron` with **`eye_highlight.png`**, drifting and glinting); then
//!   nearer still the lids (`Lids`, `lid.material.ron`: the face's material without its outline),
//!   a band of skin above each eye at rest, and the lash lines (`Lashes`, `lash.material.ron`).
//!   [`MORPH_TARGETS`] close the lids (in two steps, so the lid sliding over the curved face
//!   stays in front of the eye on the way) and turn the gaze; the lid's shadow and the upper
//!   lashes move with the lids, the iris and highlights with the gaze.
//! - **`face.facesdf.ron`** and its threshold masks (`masks/h_*.png`, `masks/v_*.png`): the SDF
//!   face map, generated by A7's generator from masks painted at every 10° of a light turning
//!   from the front to behind the head's right, and every 15° of one rising to overhead. The
//!   masks are thresholds of two angle fields ([`horizontal_threshold`],
//!   [`vertical_threshold`]): a sphere's terminator, with a nose shadow that appears past 38°,
//!   the far cheek staying lit a little longer, and eye sockets, the nose and the chin shadowed
//!   early by a top light. Monotonic by construction.
//! - **`face_base.png`** (color): skin and a small mouth; the eyes (M1 C6) and brows are meshes
//!   of their own.
//! - **`face_mask.png`** (mask, `character_maps::face_mask`): R the nose line on the nose's far
//!   side from a camera on the head's right, G highlights on the nose tip and cheeks; B (always
//!   lit) empty, the eyes being meshes (M1 C6).
//! - **`face_expression.png`** (mask, `character_maps::face_expression`): R blush on the
//!   cheeks, G gloom over the forehead and brows down to the eyes.
//! - **`face.material.ron`:** two bands, a warm rosy shade, a thin outline, skin's GI weights
//!   (spherized, skin-tinted) and the face's settings, naming the maps by their sidecars' IDs:
//!   the bangs' shadow on it (M1 C5). Its eyes draw through the bangs as eye meshes (M1 C6).
//! - **`hair.material.ron`**, **`bangs.material.ron`** (M1 C5): hair in a cool two-band shade,
//!   rounded toward the head's sphere; the cap with an angel ring, the bangs with a painted
//!   highlight band revealed by **`hair_mask.png`** (mask, `character_maps::hair_mask`: R the
//!   band's painted shape along the strands, G a slight tilt, B occlusion at the roots).
//! - **`brow.material.ron`** (M1 C5): the brows as an eye material, always lit, drawn through
//!   the bangs.
//!
//! The sandbox draws the head with `--faces` (the golden scene `faces`), listing each instance
//! as a character with a key light, a head and expression weights of its own, and posing its
//! lids and gaze through the morph targets.

